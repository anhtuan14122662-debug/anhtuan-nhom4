# Gán giá trị ban đầu cho các biến
width = 17
height = 12.0

# --- Biểu thức 1 ---
expression1_value = width // 2
print("1. width // 2")
print("   Giá trị:", expression1_value)
print("   Kiểu dữ liệu:", type(expression1_value))
print("-" * 20)

# --- Biểu thức 2 ---
expression2_value = width / 2.0
print("2. width / 2.0")
print("   Giá trị:", expression2_value)
print("   Kiểu dữ liệu:", type(expression2_value))
print("-" * 20)

# --- Biểu thức 3 ---
